// Hergebruik de standaardgenerator zodat nieuwe documenten automatisch meekomen.
const sidebarItemsGenerator: NonNullable<Options['sidebarItemsGenerator']> = ({
  defaultSidebarItemsGenerator,
  ...args
}) => defaultSidebarItemsGenerator({
  ...args,
  categoriesMetadata: {
    ...args.categoriesMetadata,
    ...Object.fromEntries(Object.entries(categories).map(([directory, [label, position]]) => [
      directory,
      {...args.categoriesMetadata[directory], label, position},
    ])),
  },
  docs: args.docs.map((doc) => {
    const presentation = documents[doc.id];
    if (!presentation) return doc;
    const [label, position] = presentation;
    return {
      ...doc,
      sidebarPosition: position,
      frontMatter: {...doc.frontMatter, sidebar_label: label},
    };
  }),
});

export default sidebarItemsGenerator;
